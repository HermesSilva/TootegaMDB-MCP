  /* Tradutor para um idioma: t('chave', arg0, arg1...). Chave ausente cai no inglês. */
  function translator(lang) {
    const table = all[lang === 'pt' ? 'pt' : 'en'];
    return function t(key) {
      let text = table[key];
      if (text === undefined) text = en[key];
      if (text === undefined) return key;
      for (let i = 1; i < arguments.length; i++) text = text.split('{' + (i - 1) + '}').join(String(arguments[i]));
      return text;
    };
  }

